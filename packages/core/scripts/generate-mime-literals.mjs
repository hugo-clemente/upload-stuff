// Generates src/utils/mime-literals.generated.ts from mime-db.
// Runtime helpers must not import mime-db.
import { writeFileSync } from "node:fs";
import { URL } from "node:url";

const dbModule = await import("mime-db");
const db = dbModule.default ?? dbModule;

const literals = Object.keys(db).sort();
const wildcards = [...new Set(literals.map((type) => type.split("/")[0]))]
  .sort()
  .map((topLevel) => `${topLevel}/*`);

const union = (items) => items.map((item) => `  | "${item}"`).join("\n");

const content = `// Generated by scripts/generate-mime-literals.mjs. DO NOT EDIT.
// Regenerate with: pnpm --filter @upload-stuff/core generate:mime

export type MimeLiteral =
${union(literals)};

export type MimeWildcard =
${union(wildcards)};
`;

writeFileSync(new URL("../src/utils/mime-literals.generated.ts", import.meta.url), content);
globalThis.console.log(`Generated ${literals.length} literals and ${wildcards.length} wildcards.`);
